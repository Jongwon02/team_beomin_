def _months_of(rng):
    """단계의 range를 그 단계가 걸치는 월 번호 집합으로 편다.

    연말~연초로 넘어가는 구간(12월~1월, yOffE=1)도 정상 처리한다.
    """
    start = rng.get("yOffS", 0) * 12 + rng["sm"]
    end = rng.get("yOffE", 0) * 12 + rng["em"]
    if end < start:                      # yOff 없이 12→1로 넘어가는 경우 방어
        end += 12
    return {((m - 1) % 12) + 1 for m in range(start, end + 1)}


def get_crop_schedule(crop, month=None):
    """작물의 재배 일정. month(1~12)를 주면 그 달에 걸치는 단계만 돌려준다.

    - month 지정: note까지 전부 포함(그 달에 뭘 해야 하는지가 질문이므로)
    - month 생략: period + task만 포함(연간 개요라 note까지 넣으면 토큰 낭비)
    """
    if crop in SCHEDULE_MISSING:
        return {"조회실패": f"'{crop}'는 아직 재배 일정 데이터가 없어요. 적합도 점수는 조회할 수 있어요."}
    data = CROP_SCHEDULE.get(crop)
    if not data:
        return {"조회실패": f"'{crop}'는 안농이 다루는 작물이 아니에요. (사과·배·오이·감자·상추)"}

    out = {"작물": crop, "출처": data["source"], "재배유형": []}
    for season in data["seasons"]:
        stages = []
        for st in season["stages"]:
            if month is not None and month not in _months_of(st["range"]):
                continue
            item = {"시기": st["period"], "작업": st["task"]}
            if month is not None:
                item["설명"] = st["note"]
            stages.append(item)
        if month is not None and not stages:
            continue
        out["재배유형"].append({
            "이름": season["name"], "기간": season["period"],
            "적합지역": season["region"], "단계": stages,
        })

    if month is not None:
        out["기준월"] = f"{month}월"
        if not out["재배유형"]:
            out["안내"] = f"{month}월에는 예정된 작업이 없어요."
    if data.get("disasters"):
        out["기상재해_주의"] = [
            {"종류": d["tag"], "시기": d["when"], "증상": d["symptom"]}
            for d in data["disasters"]
        ]
    return out


